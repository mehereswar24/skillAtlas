class ModelError(RuntimeError):
    """The model could not be reached or returned something unusable."""


class Ollama:
    """Blocking chat client. One request at a time on purpose.

    Concurrency buys nothing here — a single 7B request already saturates the
    GPU, so four in flight finish in four times the wall clock with four times
    the chance of an OOM.
    """

    def __init__(self, base_url: str, model: str, timeout: float = 300.0):
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.client = httpx.Client(timeout=timeout)
        self.calls = 0
        self.tokens = 0

    def close(self) -> None:
        self.client.close()

    def check(self) -> None:
        try:
            response = self.client.get(f"{self.base_url}/api/tags", timeout=10.0)
            response.raise_for_status()
        except httpx.HTTPError as exc:
            raise ModelError(
                f"Ollama is not reachable at {self.base_url} ({exc}). "
                f"Start it with `ollama serve`."
            ) from None
        installed = {m.get("name", "") for m in response.json().get("models", [])}
        if self.model not in installed:
            raise ModelError(
                f"Model '{self.model}' is not installed. Have: "
                f"{', '.join(sorted(installed)) or 'nothing'}. "
                f"Pull it with `ollama pull {self.model}`."
            )

    def json_chat(
        self,
        system: str,
        user: str,
        schema: dict[str, Any],
        *,
        temperature: float,
        attempts: int = 3,
    ) -> dict[str, Any]:
        payload = {
            "model": self.model,
            "stream": False,
            # A JSON schema, not just `"json"`: the sampler is constrained to
            # the grammar, so a malformed reply is impossible rather than
            # merely unlikely.
            "format": schema,
            "options": {"temperature": temperature, "num_ctx": 8192},
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
        }
        last: Exception | None = None
        for attempt in range(attempts):
            try:
                response = self.client.post(f"{self.base_url}/api/chat", json=payload)
                response.raise_for_status()
                body = response.json()
                if body.get("error"):
                    raise ModelError(str(body["error"]))
                self.calls += 1
                self.tokens += int(body.get("eval_count") or 0)
                return json.loads(body["message"]["content"])
            except (httpx.HTTPError, json.JSONDecodeError, KeyError, ModelError) as exc:
                last = exc
                if attempt + 1 < attempts:
                    time.sleep(2 * (attempt + 1))
        raise ModelError(f"model call failed after {attempts} attempts: {last}")


