@dataclass(frozen=True)
class Target:
    """A concept, flattened out of the ORM.

    The generation loop runs for hours. Holding a SQLAlchemy session open for
    that long keeps a SQLite read transaction alive and blocks the seeder from
    writing, so everything the loop needs is copied out and the session closed
    before the first model call.
    """

    slug: str
    name: str
    body: str
    track: str


def select_targets(db: Session) -> tuple[list[Target], dict[str, Target]]:
    """The priority queue, plus every concept keyed by slug.

    The queue is ordered by how likely a learner is to hit the concept: the DSA
    track, then the role roadmaps in the order they are picked, then anything a
    company's focus areas or a project points at. Covering all 2,757 concepts
    with a local 7B model would take days; covering the ~250 that appear on
    real routes takes hours and closes the gap where it is visible.

    The second return value exists so ``--only`` and ``--concepts`` can name a
    concept outside that priority set — the ordering is a default, not a fence.
    """
    tracks = db.scalars(select(Track).order_by(Track.sort_order)).all()
    by_slug = {t.slug: t for t in tracks}

    members: dict[str, list[Concept]] = {}
    for track in tracks:
        rows = db.scalars(
            select(Concept)
            .join(TrackConcept, TrackConcept.concept_id == Concept.id)
            .where(TrackConcept.track_id == track.id)
            .order_by(TrackConcept.sort_order)
        ).all()
        members[track.slug] = list(rows)

    ordered: list[str] = [s for s in by_slug if s.startswith(DSA_PREFIX)]
    ordered += [s for s in ROLE_TRACKS if s in by_slug and s not in ordered]

    targets: "OrderedDict[str, Target]" = OrderedDict()
    for track_slug in ordered:
        for concept in members.get(track_slug, []):
            targets.setdefault(concept.slug, _target(concept, track_slug))

    # Whatever the company pages and the projects point at, if a role roadmap
    # has not already claimed it. These are few, and they are exactly the
    # concepts a learner lands on from outside a route.
    referenced: list[Concept] = []
    referenced += list(
        db.scalars(
            select(Concept)
            .join(CompanyFocus, CompanyFocus.concept_id == Concept.id)
            .order_by(Concept.slug)
        ).unique()
    )
    referenced += list(
        db.scalars(
            select(Concept)
            .join(Project, Project.concept_id == Concept.id)
            .order_by(Concept.slug)
        ).unique()
    )
    def home_of(concept: Concept) -> str:
        """The file a concept's questions belong in: its highest-priority track."""
        return next(
            (s for s in ordered if concept in members.get(s, [])),
            None,
        ) or next(
            (t.slug for t in tracks if concept in members.get(t.slug, [])),
            concept.domain.slug,
        )

    for concept in referenced:
        if concept.slug in targets:
            continue
        targets[concept.slug] = _target(concept, home_of(concept))

    everything = dict(targets)
    for concept in db.scalars(select(Concept).order_by(Concept.slug)).unique():
        everything.setdefault(concept.slug, _target(concept, home_of(concept)))

    return list(targets.values()), everything


def _target(concept: Concept, track: str) -> Target:
    text = (concept.content_md or "").strip()
    summary = (concept.summary or "").strip()
    if summary and summary not in text:
        text = f"{summary}\n\n{text}"
    return Target(
        slug=concept.slug, name=concept.name, body=text[:MAX_BODY_CHARS], track=track
    )


# --------------------------------------------------------------------------
# YAML store — one file per track, and the resume checkpoint
# --------------------------------------------------------------------------

FILE_HEADER = """\
# Concept quizzes and interview questions - {track}
#
# Generated by scripts/generate_quizzes.py against each concept's own
# content_md, then re-checked question by question against that same body;
# anything the body could not support was discarded. Loaded by
# app.seed.loader.seed_quizzes and keyed by concept slug.
#
# This file is authored content and belongs in git. Do not move it into
# app/seed/tracks/, which the roadmap.sh importer regenerates.
"""


class QuizStore:
    """The `quizzes/*.yaml` set, treated as both output and progress log."""

    def __init__(self, out_dir: Path):
        self.out_dir = out_dir
        self.files: dict[str, dict[str, Any]] = {}
        self.home: dict[str, str] = {}
        if out_dir.exists():
            for path in sorted(out_dir.glob("*.yaml")):
                data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
                concepts = data.get("concepts") or {}
                self.files[path.stem] = concepts
                for slug in concepts:
                    self.home[slug] = path.stem

    def covered(self) -> set[str]:
        return set(self.home)

    def put(self, track: str, slug: str, payload: dict[str, Any]) -> None:
        # A slug may only live in one file, or the loader rejects the set.
        previous = self.home.get(slug)
        if previous is not None and previous != track:
            self.files[previous].pop(slug, None)
            self._write(previous)
        self.files.setdefault(track, {})[slug] = payload
        self.home[slug] = track
        self._write(track)

    def _write(self, track: str) -> None:
        self.out_dir.mkdir(parents=True, exist_ok=True)
        concepts = self.files[track]
        body = yaml.safe_dump(
            {"concepts": {k: concepts[k] for k in sorted(concepts)}},
            sort_keys=False,
            allow_unicode=True,
            width=100,
            default_flow_style=False,
        )
        text = FILE_HEADER.format(track=track) + "\n" + body
        # Write beside the target and replace: an interrupt during the write of
        # a 200 KB file must not leave a truncated one behind, since this file
        # is the only record of several hours of generation.
        tmp = self.out_dir / f".{track}.yaml.tmp"
        tmp.write_text(text, encoding="utf-8")
        tmp.replace(self.out_dir / f"{track}.yaml")


# --------------------------------------------------------------------------
# structural filtering — the cheap rejections, before the model is consulted
# --------------------------------------------------------------------------


def _clean(text: Any) -> str:
    return re.sub(r"\s+", " ", str(text or "")).strip()


def _option_text(text: Any) -> str:
    """One option, without the letter the model may have prefixed it with."""
    return OPTION_LABEL.sub("", _clean(text)).strip()


def structural_reject(question: dict[str, Any]) -> str | None:
    """Why this question is unusable, or None if it survives."""
    prompt = _clean(question.get("prompt"))
    options = [_option_text(o) for o in question.get("options") or []]
    index = question.get("correct_index")
    explanation = _clean(question.get("explanation"))

    if len(prompt) < 15:
        return "prompt too short"
    if len(options) < 4:
        return "fewer than four options"
    if any(not o for o in options):
        return "blank option"
    if len({o.casefold() for o in options}) != len(options):
        return "duplicate options"
    if not isinstance(index, int) or not 0 <= index < len(options):
        return "correct_index out of range"
    if len(explanation) < 30:
        return "explanation too thin"
    if any(pattern.search(prompt) for pattern in VOCAB_PATTERNS):
        return "vocabulary recall, not understanding"
    if any(LAZY_OPTIONS.match(o) for o in options):
        return "'all of the above'-style option"
    # An option that is far longer than the rest gives the answer away.
    longest = max(options, key=len)
    if len(longest) > 3 * min(len(o) for o in options) and len(longest) > 60:
        return "correct option is conspicuously longer"
    return None


def structural_reject_interview(question: dict[str, Any]) -> str | None:
    text = _clean(question.get("question"))
    answer = _clean(question.get("answer_md"))
    if len(text) < 15:
        return "question too short"
    if len(answer) < 120:
        return "answer too thin to be useful"
    if answer.casefold().startswith(text.casefold()[:40]):
        return "answer restates the question"
    if any(pattern.search(text) for pattern in VOCAB_PATTERNS):
        return "vocabulary recall, not understanding"
    return None


# --------------------------------------------------------------------------
# generation + verification
# --------------------------------------------------------------------------


class Tally:
    def __init__(self) -> None:
        self.generated_quiz = 0
        self.generated_interview = 0
        self.structural_quiz = 0
        self.structural_interview = 0
        self.unsupported_quiz = 0
        self.unsupported_interview = 0
        self.kept_quiz = 0
        self.kept_interview = 0

    @property
    def generated(self) -> int:
        return self.generated_quiz + self.generated_interview

    @property
    def kept(self) -> int:
        return self.kept_quiz + self.kept_interview

    @property
    def rejected(self) -> int:
        return self.generated - self.kept


def generate(model: Ollama, target: Target, temperature: float) -> dict:
    return model.json_chat(
        GENERATE_SYSTEM,
        GENERATE_USER.format(
            name=target.name,
            body=target.body,
            n_quiz=ASK_QUIZ,
            n_interview=ASK_INTERVIEW,
        ),
        GENERATE_SCHEMA,
        temperature=temperature,
    )


def verify_quiz(model: Ollama, target: Target, q: dict) -> tuple[bool, str]:
    options = [_option_text(o) for o in q["options"]]
    listed = "\n".join(
        f"{chr(65 + i)}. {text}" for i, text in enumerate(options)
    )
    verdict = model.json_chat(
        VERIFY_QUIZ_SYSTEM,
        VERIFY_QUIZ_USER.format(
            name=target.name,
            body=target.body,
            prompt=_clean(q["prompt"]),
            options=listed,
            answer=options[q["correct_index"]],
        ),
        VERDICT_SCHEMA,
        temperature=0.0,
    )
    return bool(verdict.get("supported")), _clean(verdict.get("reason"))


def verify_interview(model: Ollama, target: Target, q: dict) -> tuple[bool, str]:
    verdict = model.json_chat(
        VERIFY_INTERVIEW_SYSTEM,
        VERIFY_INTERVIEW_USER.format(
            name=target.name,
            body=target.body,
            question=_clean(q["question"]),
            answer=str(q["answer_md"]).strip(),
        ),
        VERDICT_SCHEMA,
        temperature=0.0,
    )
    return bool(verdict.get("supported")), _clean(verdict.get("reason"))


def build_for_concept(
    model: Ollama,
    target: Target,
    tally: Tally,
    *,
    attempts: int,
    verbose: bool,
) -> dict[str, Any] | None:
    """Generate, filter, verify. Returns None when too little survived."""
    quiz: list[dict[str, Any]] = []
    interview: list[dict[str, Any]] = []
    seen_prompts: set[str] = set()
    seen_questions: set[str] = set()

    for attempt in range(attempts):
        if len(quiz) >= MIN_QUIZ and len(interview) >= MIN_INTERVIEW:
            break
        # Nudge the temperature up on a retry: repeating the first pass at the
        # same setting mostly reproduces the questions that were just rejected.
        raw = generate(model, target, temperature=0.3 + 0.2 * attempt)

        for q in raw.get("quiz") or []:
            if len(quiz) >= KEEP_QUIZ_MAX:
                break
            tally.generated_quiz += 1
            key = _clean(q.get("prompt")).casefold()
            if key in seen_prompts:
                tally.structural_quiz += 1
                continue
            seen_prompts.add(key)
            why = structural_reject(q)
            if why:
                tally.structural_quiz += 1
                if verbose:
                    print(f"      drop mcq  [{why}] {_clean(q.get('prompt'))[:70]}")
                continue
            supported, reason = verify_quiz(model, target, q)
            if not supported:
                tally.unsupported_quiz += 1
                if verbose:
                    print(f"      drop mcq  [unsupported] {reason[:90]}")
                continue
            options = [_option_text(o) for o in q["options"]]
            quiz.append(
                {
                    "prompt": _clean(q["prompt"]),
                    "explanation": _clean(q["explanation"]),
                    "options": [
                        {"text": text, "correct": True}
                        if i == q["correct_index"]
                        else {"text": text}
                        for i, text in enumerate(options)
                    ],
                }
            )
            tally.kept_quiz += 1

        for q in raw.get("interview") or []:
            if len(interview) >= KEEP_INTERVIEW_MAX:
                break
            tally.generated_interview += 1
            key = _clean(q.get("question")).casefold()
            if key in seen_questions:
                tally.structural_interview += 1
                continue
            seen_questions.add(key)
            why = structural_reject_interview(q)
            if why:
                tally.structural_interview += 1
                if verbose:
                    print(f"      drop iq   [{why}] {_clean(q.get('question'))[:70]}")
                continue
            supported, reason = verify_interview(model, target, q)
            if not supported:
                tally.unsupported_interview += 1
                if verbose:
                    print(f"      drop iq   [unsupported] {reason[:90]}")
                continue
            difficulty = str(q.get("difficulty") or "medium").lower()
            interview.append(
                {
                    "question": _clean(q["question"]),
                    "answer_md": str(q["answer_md"]).strip(),
                    "difficulty": difficulty
                    if difficulty in DIFFICULTIES
                    else "medium",
                }
            )
            tally.kept_interview += 1

    if len(quiz) < MIN_QUIZ or len(interview) < MIN_INTERVIEW:
        # Roll back what did survive: a two-question quiz that a learner can
        # pass by guessing is a worse gate than the honest no-gate fallback.
        tally.kept_quiz -= len(quiz)
        tally.kept_interview -= len(interview)
        return None

    return {
        "generated_by": model.model,
        "verified_at": datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z"),
        "quiz": quiz,
        "interview": interview,
    }


