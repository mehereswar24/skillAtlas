def _read_slug_file(path: Path) -> list[str]:
    slugs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            slugs.append(line)
    return slugs


def _filter(
    targets: list[Target],
    everything: dict[str, Target],
    *,
    only: list[str],
    from_file: Path | None,
) -> list[Target]:
    """Narrow the priority queue to an explicitly named set, if one was given.

    Named slugs are resolved against every concept, not just the priority set,
    so a run can cover something the ordering has not reached yet. An unknown
    slug is fatal rather than skipped: silently generating for four of the five
    concepts you asked for is the kind of thing you only notice much later.
    """
    wanted: list[str] = list(only)
    if from_file is not None:
        wanted += _read_slug_file(from_file)
    if not wanted:
        return targets

    picked: list[Target] = []
    missing: list[str] = []
    for slug in dict.fromkeys(wanted):
        if slug in everything:
            picked.append(everything[slug])
        else:
            missing.append(slug)
    if missing:
        raise SystemExit("No such concept: " + ", ".join(missing))
    return picked


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate and verify concept quizzes with a local Ollama model."
    )
    parser.add_argument("--limit", type=int, default=250,
                        help="stop after this many concepts (default: 250)")
    parser.add_argument("--only", action="append", default=[], metavar="SLUG",
                        help="generate for this concept only; repeatable")
    parser.add_argument("--concepts", type=Path, metavar="FILE",
                        help="file of concept slugs, one per line (# comments ok)")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL)
    parser.add_argument("--attempts", type=int, default=2,
                        help="generation passes per concept before giving up")
    parser.add_argument("--force", action="store_true",
                        help="regenerate concepts that already have questions")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the plan and exit without calling the model")
    parser.add_argument("--quiet", action="store_true",
                        help="do not print each rejected question")
    args = parser.parse_args(list(argv) if argv is not None else None)

    # Read the plan, then let go of the database. The loop below runs for hours
    # and would otherwise hold a SQLite read transaction open the whole time,
    # blocking `python -m app.seed.loader` from ever committing.
    db = SessionLocal()
    try:
        priority, everything = select_targets(db)
        targets = _filter(
            priority, everything, only=args.only, from_file=args.concepts
        )
    finally:
        db.close()

    store = QuizStore(OUT_DIR)
    covered = store.covered()

    queue: list[Target] = []
    skipped_short: list[str] = []
    for target in targets:
        if target.slug in covered and not args.force:
            continue
        if len(target.body) < MIN_BODY_CHARS:
            skipped_short.append(target.slug)
            continue
        queue.append(target)
        if len(queue) >= args.limit:
            break

    print(f"{len(targets)} concepts in the target set, "
          f"{len(covered)} already covered, "
          f"{len(skipped_short)} skipped as too short to ground a question.")
    print(f"Queue: {len(queue)} concepts.")
    if args.dry_run:
        for target in queue:
            print(f"  {target.track:20} {target.slug}")
        return 0
    if not queue:
        return 0

    model = Ollama(args.base_url, args.model)
    model.check()

    tally = Tally()
    done = thin = 0
    started = time.time()
    try:
        for position, target in enumerate(queue, start=1):
            elapsed = time.time() - started
            rate = elapsed / max(position - 1, 1)
            eta = rate * (len(queue) - position + 1) / 60
            print(f"[{position}/{len(queue)}] {target.slug} "
                  f"({target.track}, ~{eta:.0f} min left)", flush=True)
            try:
                payload = build_for_concept(
                    model, target, tally,
                    attempts=args.attempts, verbose=not args.quiet,
                )
            except ModelError as exc:
                print(f"      SKIPPED: {exc}", flush=True)
                continue
            if payload is None:
                thin += 1
                print("      SKIPPED: too little survived verification", flush=True)
                continue
            store.put(target.track, target.slug, payload)
            done += 1
            print(f"      kept {len(payload['quiz'])} mcq + "
                  f"{len(payload['interview'])} interview", flush=True)
    except KeyboardInterrupt:
        print("\nInterrupted. Everything finished so far is already on disk; "
              "re-run to continue.")

    minutes = (time.time() - started) / 60
    rate = 100 * tally.rejected / tally.generated if tally.generated else 0.0
    unsupported = tally.unsupported_quiz + tally.unsupported_interview
    print(
        f"\n{done} concepts written, {thin} left uncovered "
        f"(too little survived), in {minutes:.0f} min.\n"
        f"Questions generated:   {tally.generated} "
        f"({tally.generated_quiz} mcq, {tally.generated_interview} interview)\n"
        f"Kept:                  {tally.kept} "
        f"({tally.kept_quiz} mcq, {tally.kept_interview} interview)\n"
        f"Rejected structurally: "
        f"{tally.structural_quiz + tally.structural_interview}\n"
        f"Rejected as unsupported by their own source: {unsupported}\n"
        f"Overall rejection rate: {rate:.1f}%\n"
        f"Model calls: {model.calls}, {model.tokens} tokens generated."
    )
    model.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
