"""Generate concept quizzes and interview questions with the local model.

roadmap.sh publishes no assessment material, so every concept imported from it
arrives with an empty quiz. ``routers/progress.py`` treats a concept with no
questions as automatically passed, which means the product's central promise —
that every step ends in a check — is currently false for all 2,757 of them.
This script fills that gap.

Two passes, and the second one is the point
-------------------------------------------
A 7B model asked for five multiple-choice questions about a topic will happily
produce five, whether or not the text in front of it supports them. It pads
with things it knows from pre-training, invents specifics the passage never
states, and occasionally writes a "correct" option that is simply wrong. A
question whose answer cannot be found in the material the learner just read is
worse than no question at all: it fails people for not knowing something the
product never taught them.

So generation is followed by a **grounding check**. Each question is sent back
alone, in a fresh context, with the concept body and its own stated answer, and
the model is asked whether that body actually establishes the answer. Anything
that comes back unsupported is discarded rather than repaired — a rewrite would
be the same model marking its own homework twice. The rejection rate is printed
at the end because it is the honest measure of how much of the first pass was
bluff.

The two question types are held to different bars, which matters more than it
sounds. A multiple-choice question is a *gate*: a learner is failed for getting
it wrong, so nothing beyond the material they were given may be required, and
every distractor has to be defensibly wrong. An interview answer is a *worked
example*, and a good one explains somewhat beyond the notes it came from —
holding it to the quiz standard rejects roughly nine answers in ten for being
fuller than their source rather than for being wrong. It is checked instead for
being correct, on-topic, and free of specifics the source cannot back.

Structural rules are enforced *before* the model is consulted (cheap rejections
first): four distinct options, exactly one marked correct, a real explanation,
no "all of the above", and no vocabulary-recall prompts such as "what does REST
stand for" — which a 7B model reaches for constantly and which test nothing.

Output
------
Authored YAML under ``app/seed/quizzes/<track>.yaml``, keyed by concept slug,
loaded by ``app.seed.loader.seed_quizzes``. Deliberately *not* under
``app/seed/tracks/``: that directory is machine-generated by
``scripts/import_roadmapsh.py``, is git-ignored for licence reasons, and is
overwritten wholesale on the next import. These questions are ours and have to
survive that.

Resuming
--------
The YAML *is* the checkpoint. Each concept is appended and the file rewritten
atomically the moment it is done, so an interrupted run loses at most the
concept in flight. Re-running skips every slug already present, which also
makes this safe to run repeatedly as the target list grows. ``--force``
regenerates concepts that are already covered.

Usage::

    python scripts/generate_quizzes.py --limit 250
    python scripts/generate_quizzes.py --only backend-introduction --force
    python scripts/generate_quizzes.py --concepts my-slugs.txt
    python scripts/generate_quizzes.py --dry-run          # show the plan only
"""

